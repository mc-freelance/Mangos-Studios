        // Build a field definition from its seed metadata and expansion variants.
        private static FieldDefinitionSeed Create(
            string sourceKey,
            string columnName,
            string description)
        {
            return CreatureTemplateFieldDataFactory.Select(
                sourceKey,
                columnName,
                description,
                FieldDataSeedFactory.Variant(
                    "generation-0-vanilla",
                    new[] { 0 },
                    "Vanilla faction template values.",
                    VanillaOptions),
                FieldDataSeedFactory.Variant(
                    "generation-1-tbc",
                    new[] { 1 },
                    "The Burning Crusade faction template values.",
                    TbcOptions),
                FieldDataSeedFactory.Variant(
                    "generation-2-wrath",
                    new[] { 2 },
                    "Wrath of the Lich King faction template values.",
                    WrathOptions),
                FieldDataSeedFactory.Variant(
                    "generation-3-cataclysm",
                    new[] { 3 },
                    "Cataclysm faction template values.",
                    CataclysmOptions));
        }

